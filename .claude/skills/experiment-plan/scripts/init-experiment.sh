#!/bin/sh
# 生成实验目录骨架。确定性部分全部由本脚本产出，模型只负责填语义内容。
#
# 用法: init-experiment.sh <slug> [标题]
#   slug  kebab-case 英文，不含日期前缀
#   标题  可选，默认用 slug
#
# 目标仓库由 git 仓库根决定，且必须含 experiments/ 目录。

set -eu

slug=${1:-}
title=${2:-}

if [ -z "$slug" ]; then
	echo "用法: init-experiment.sh <slug> [标题]" >&2
	exit 2
fi

case "$slug" in
	*[!a-z0-9-]* | -* | *- | "")
		echo "错误: slug 必须是 kebab-case 小写英文，不能以 - 开头或结尾: $slug" >&2
		exit 2
		;;
esac

lab_root=$(git rev-parse --show-toplevel 2>/dev/null) || {
	echo "错误: 当前目录不在 git 仓库内，无法定位 lab 仓库" >&2
	exit 1
}

if [ ! -d "$lab_root/experiments" ]; then
	echo "错误: $lab_root 下没有 experiments/ 目录，这不是 lab 仓库" >&2
	echo "      绝不在其他仓库里建 experiments/。请切换到 lab 仓库后重试。" >&2
	exit 1
fi

ym=$(date +%Y-%m)
dir="$lab_root/experiments/$ym-$slug"

if [ -e "$dir" ]; then
	echo "错误: $dir 已存在，不覆盖" >&2
	exit 1
fi

[ -n "$title" ] || title="$slug"

mkdir -p "$dir"

# README：七段骨架。标题文本是 content-forge 的解析接口，由脚本生成以保证逐字一致。
cat > "$dir/README.md" <<EOF
# $title

## Question

<!-- 一句话。一个能判对错的问题，不是意图声明。开跑前填。 -->

## Setup

<!-- 工具、版本、环境、任务、判据。写到别人能复现。开跑前填。 -->

## Log

<!-- 跑的过程中记，允许混乱。卡在哪、报什么错、当时怎么想的。 -->

## Data

<!-- 跑完从 data/ 汇总成表。没测到的写「待补」，绝不估算。 -->

## What Worked

<!-- 有效的，带条件：什么情况下有效。 -->

## What Failed

<!-- 失败的，带原因。这段往往比上一段更有内容价值，不许为了好看删。 -->

## 有效性与可复制性

<!-- 一张表，每行一个「这次试过的做法」。这是整份 README 里唯一能一眼看完的东西——
     其余几段都要读一整段才知道结论。

     | 实践 | 是否有效 | 是否可复制 | 证据 |

     两列分开判：有效说的是这次成不成，可复制说的是换个人换个题目还成不成。
     一次性的运气、只在这台机器上成立的做法，可以「有效」但「不可复制」。

     必须包含无效的那些行，而且它们通常是这次实验真正的产出——有效的多半能从
     以往经验推出来，无效的只有真跑一遍才知道。为了表好看把失败行删掉，
     等于把实验最贵的部分扔了。 -->

## Conclusion

<!-- 只能人写。agent 可给候选，但必须由人改写，不是点头批准。 -->

<!-- 可选第八段：产生了可复用成果时，在此后追加 "## Artifacts"，写指针表（成果 | 位置 | 状态），不要把成果拷进本目录。 -->
EOF

# content-outline.md：实验前即可确认的叙事骨架。只允许写已知背景，不能预填结果。
cat > "$dir/content-outline.md" <<EOF
# 内容骨架：$title

**状态：** 待作者确认（开跑前必须确认）

## 已知背景

<!-- 为什么现在做这件事？已经发生且可公开的处境、限制或动机。不要写实验结果。 -->

## 想回答的问题

<!-- 面向读者的一个问题。应与 README Question 一致，但可以用非技术语言表达。 -->

## 读者与价值

<!-- 谁会在意？读完后能获得什么判断或行动线索？ -->

## 已知困难与边界

<!-- 开跑前已知的人工成本、账号/素材限制、风险或不确定性。 -->

## 预期叙事骨架

<!-- 背景 → 要验证什么 → 过程中的证据（待实验补）→ 结果与限制（待实验补）。
不要填「一定会证明什么」。 -->

## 作者确认

<!-- 确认后填写：已确认：是；日期：YYYY-MM-DD。未确认不得开跑。 -->
EOF

# plan.md：固定骨架 + 产物时间轴。时间轴是确定性内容，写死在这里，不由模型生成。
cat > "$dir/plan.md" <<EOF
# 实验剧本：$title

## 产物时间轴

| 时刻 | 产生什么 | 谁 |
| --- | --- | --- |
| 开跑前（现在） | \`README.md\` 骨架 + 本文件 | init-experiment.sh |
| 每步开始 | 记下开始时间 | 你 |
| **跑的过程中** | \`notes/\` \`recordings/\` \`data/\` ← **唯一产生窗口，错过补不回来** | 你 |
| 跑完 | README 的 Log / Data / What Worked / What Failed | agent 起草，你核对 |
| 跑完 | README 的「有效性与可复制性」表 | agent 起草，你核对每行的判断 |
| 跑完 | README 的 Conclusion | **只能你写** |
| 产生可复用成果时 | README 的 Artifacts 段（写指针，不拷贝） | 你 |
| 最后 | \`drafts/\` | content-forge |

跑完之后本文件**冻结，一个字不许改**。它的价值是留下开跑前的判断，改了就只剩马后炮。

## 判据

<!-- 怎么算这次实验有结论。开跑前写死，跑的过程中不许改。 -->

## 预期反直觉点

<!-- 你预期会推翻什么。跑完回来对照，猜错了本身就是内容。 -->
<!-- 若本实验为回溯补记，删除本节，改写为「实际发现」，并在文件顶部标明。 -->

## 步骤

| # | 做什么 | 交付物 | 记什么数据 | 录哪段 |
| --- | --- | --- | --- | --- |
| 1 | | | | |

<!-- 「记什么数据」不许留空。每步必须有交付物，说不出交付物的步骤是想象。 -->

## 数据字段

| 字段 | 单位 | 记录时机 | 本次值 |
| --- | --- | --- | --- |
| 单步耗时 | 分钟 | 每步开始/结束 | |
| 总耗时 | 分钟 | 收尾 | |
| token 消耗 | token | 收尾 | |
| 失败次数 | 次 | 发生时 | |
| 需人工干预次数 | 次 | 发生时 | |
| 主观评分 | 1-5 | 收尾 | |

## 录制清单

<!-- 按 NN-描述.cast 命名列出计划录的片段。哪些必录，哪些可选。 -->

## 已知风险

<!-- 可能卡住的地方、可能拿不到数据的地方。 -->
EOF

echo "$dir"
echo "  README.md  七段骨架（标题由脚本生成，逐字一致）" >&2
echo "  plan.md    含产物时间轴" >&2
echo "  content-outline.md  开跑前确认的内容骨架" >&2
